#define CHECK(condition) \
	do \
	{ \
		if (!(condition)) \
		{ \
			std::fprintf(stderr, "%s:%d: check failed: %s\n", __FILE__, __LINE__, #condition); \
			++failures; \
		} \
	} while (0)

// What the streams below decompress to: 1500 bytes of words chosen by a small generator.
std::vector<uint8_t> payload()
{
	static const char *const words[] = { "sonic", "tails", "knuckles", "emerald", "ring", "spring", "zone", "act", "boss", "egg" };
	std::vector<uint8_t> out;
	uint32_t x = 12345;
	while (out.size() < 1500)
	{
		x = (x * 1103515245u + 12345u) & 0x7fffffffu;
		for (const char *c = words[(x >> 16) % 10]; *c; ++c)
			out.push_back(static_cast<uint8_t>(*c));
		out.push_back(' ');
	}
	out.resize(1500);
	return out;
}

