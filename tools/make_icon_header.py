#!/usr/bin/env python3
"""Regenerate the icon files from assets/icon/icon.png.

Writes
  assets/icon/sonic-pocket.ico   the Windows icon (256, 128, 64, 48, 32 and 16 pixels),
                                 compiled into sonic-pocket.exe by assets/icon/sonic-pocket.rc
  src/apps/window_icon.h         a 64x64 RGBA copy for SDL_SetWindowIcon (macOS and Linux
                                 windows; there is no icon resource to read there)

Needs ImageMagick (`magick`) on the PATH. Run it from anywhere:

    python tools/make_icon_header.py
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "icon" / "icon.png"
ICO = ROOT / "assets" / "icon" / "sonic-pocket.ico"
HEADER = ROOT / "src" / "apps" / "window_icon.h"
SIZE = 64


def magick(*args):
    try:
        return subprocess.run(["magick", *map(str, args)], check=True, capture_output=True).stdout
    except FileNotFoundError:
        sys.exit("ImageMagick (magick) is needed to make the icon files")
    except subprocess.CalledProcessError as error:
        sys.exit(f"magick failed: {error.stderr.decode(errors='replace')}")


def main():
    if not SOURCE.is_file():
        sys.exit(f"{SOURCE} is missing")

    magick(SOURCE, "-background", "none", "-define", "icon:auto-resize=256,128,64,48,32,16", ICO)

    rgba = magick(SOURCE, "-background", "none", "-resize", f"{SIZE}x{SIZE}",
                  "-gravity", "center", "-extent", f"{SIZE}x{SIZE}", "-depth", "8", "rgba:-")
    if len(rgba) != SIZE * SIZE * 4:
        sys.exit(f"expected {SIZE * SIZE * 4} bytes of pixels, got {len(rgba)}")

    lines = []
    for start in range(0, len(rgba), 16):
        lines.append("\t" + ", ".join(f"0x{byte:02x}" for byte in rgba[start:start + 16]) + ",")
    HEADER.write_text(
        "// Generated by tools/make_icon_header.py from assets/icon/icon.png. Do not edit.\n"
        "//\n"
        "// The window icon as 8-bit RGBA, row by row, for SDL_SetWindowIcon.\n"
        "#pragma once\n"
        "\n"
        "#include <cstdint>\n"
        "\n"
        f"constexpr int WINDOW_ICON_SIZE = {SIZE};\n"
        "\n"
        "constexpr uint8_t WINDOW_ICON_RGBA[WINDOW_ICON_SIZE * WINDOW_ICON_SIZE * 4] = {\n"
        + "\n".join(lines) + "\n};\n",
        newline="\n",
    )
    print(f"wrote {ICO.relative_to(ROOT)} and {HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
